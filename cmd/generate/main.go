package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
	"unicode"
)

type OpenAPISpec struct {
	Paths map[string]struct {
		Post struct {
			OperationID string `json:"operationId"`
			RequestBody *struct {
				Content struct {
					JSON struct {
						Schema struct {
							Properties map[string]OpenAPIProperty `json:"properties"`
							Required   []string                   `json:"required"`
						} `json:"schema"`
					} `json:"application/json"`
				} `json:"content"`
			} `json:"requestBody"`
		} `json:"post"`
	} `json:"paths"`
}

type OpenAPIProperty struct {
	Type        string            `json:"type"`
	Description string            `json:"description"`
	Enum        []string          `json:"enum"`
	AnyOf       []OpenAPIProperty `json:"anyOf"`
	Items       *OpenAPIProperty  `json:"items"`
}

func main() {
	check := flag.Bool("check", false, "fail if models_gen.go differs from generated output")
	flag.Parse()

	var err error
	if *check {
		err = checkGenerated()
	} else {
		err = generate()
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "model generation failed:", err)
		os.Exit(1)
	}
}

func generate() error {
	generated, err := generateFromSpec()
	if err != nil {
		return err
	}
	if err := os.WriteFile("models_gen.go", generated, 0644); err != nil {
		return fmt.Errorf("write models_gen.go: %w", err)
	}
	return nil
}

func checkGenerated() error {
	generated, err := generateFromSpec()
	if err != nil {
		return err
	}
	current, err := os.ReadFile("models_gen.go")
	if err != nil {
		return fmt.Errorf("read models_gen.go: %w", err)
	}
	if !bytes.Equal(current, generated) {
		return fmt.Errorf("models_gen.go is out of date; run make generate")
	}
	return nil
}

func generateFromSpec() ([]byte, error) {
	data, err := os.ReadFile("spec/openapi.json")
	if err != nil {
		return nil, fmt.Errorf("read OpenAPI spec: %w", err)
	}
	var spec OpenAPISpec
	if err := json.Unmarshal(data, &spec); err != nil {
		return nil, fmt.Errorf("decode OpenAPI spec: %w", err)
	}
	generated, err := generateSource(spec)
	if err != nil {
		return nil, err
	}
	return generated, nil
}

func generateSource(spec OpenAPISpec) ([]byte, error) {
	if len(spec.Paths) == 0 {
		return nil, fmt.Errorf("OpenAPI spec has no paths")
	}

	var b strings.Builder
	b.WriteString("// Code generated by cmd/generate; DO NOT EDIT.\n\npackage warera\n\n")
	b.WriteString("// CursorPage represents a generic cursor-paginated page of items.\n")
	b.WriteString("type CursorPage[T any] struct {\n")
	b.WriteString("\tItems []T `json:\"items\"`\n")
	b.WriteString("\tNextCursor string `json:\"nextCursor,omitempty\"`\n")
	b.WriteString("}\n\n")
	b.WriteString("// Request and filter models generated from spec/openapi.json.\n\n")

	filterNames := map[string]string{
		"company.getCompanies":                          "CompanyFilter",
		"article.getArticlesPaginated":                  "ArticleFilter",
		"battle.getBattles":                             "BattleFilter",
		"user.getUsersByCountry":                        "UserFilter",
		"mu.getManyPaginated":                           "MUFilter",
		"event.getEventsPaginated":                      "EventFilter",
		"transaction.getPaginatedTransactions":          "TransactionFilter",
		"workOffer.getWorkOffersPaginated":              "WorkOfferFilter",
		"mercenaryContractAuction.getPaginatedAuctions": "AuctionFilter",
	}

	paths := make([]string, 0, len(spec.Paths))
	for path := range spec.Paths {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	generatedNames := make(map[string]string)

	for _, path := range paths {
		pathItem := spec.Paths[path]
		body := pathItem.Post.RequestBody
		if body == nil || len(body.Content.JSON.Schema.Properties) == 0 {
			continue
		}
		opID := pathItem.Post.OperationID
		if opID == "" {
			opID = strings.TrimPrefix(path, "/")
		}
		props := body.Content.JSON.Schema.Properties
		structName, known := filterNames[opID]
		if !known {
			_, hasLimit := props["limit"]
			_, hasPerPage := props["perPage"]
			_, hasCursor := props["cursor"]
			if len(props) < 2 && !hasLimit && !hasPerPage && !hasCursor {
				continue
			}
			structName = deriveFilterName(opID)
		}
		if previous, exists := generatedNames[structName]; exists {
			return nil, fmt.Errorf("operation %s and %s both generate %s", previous, opID, structName)
		}
		generatedNames[structName] = opID

		required := make(map[string]bool, len(body.Content.JSON.Schema.Required))
		for _, property := range body.Content.JSON.Schema.Required {
			required[property] = true
		}
		propertyNames := make([]string, 0, len(props))
		for name := range props {
			propertyNames = append(propertyNames, name)
		}
		sort.Strings(propertyNames)

		fmt.Fprintf(&b, "// %s specifies query and filter options for %s.\n", structName, opID)
		fmt.Fprintf(&b, "type %s struct {\n", structName)
		fieldNames := make(map[string]string, len(props))
		for _, name := range propertyNames {
			property := props[name]
			fieldName := toGoFieldName(name)
			if previous, exists := fieldNames[fieldName]; exists {
				return nil, fmt.Errorf("operation %s properties %q and %q both map to Go field %s", opID, previous, name, fieldName)
			}
			fieldNames[fieldName] = name
			goType, err := goTypeFromOpenAPI(property)
			if err != nil {
				return nil, fmt.Errorf("operation %s property %s: %w", opID, name, err)
			}
			if property.Type == "boolean" && !required[name] {
				goType = "*bool" // Preserve the distinction between omitted and false.
			}
			if goType == "StringOrStrings" && !required[name] {
				goType = "*StringOrStrings"
			}
			tag := fmt.Sprintf("json:\"%s,omitempty\"", name)
			if required[name] {
				tag = fmt.Sprintf("json:\"%s\"", name)
			}
			comment := strings.Join(strings.Fields(property.Description), " ")
			if comment != "" {
				comment = " // " + comment
			}
			fmt.Fprintf(&b, "\t%s %s `%s`%s\n", fieldName, goType, tag, comment)
		}
		b.WriteString("}\n\n")
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return formatted, nil
}

func deriveFilterName(opID string) string {
	parts := strings.Split(opID, ".")
	if len(parts) < 2 {
		return capitalize(opID) + "Filter"
	}
	method := strings.TrimPrefix(parts[1], "get")
	method = strings.TrimSuffix(method, "Paginated")
	return capitalize(parts[0]) + capitalize(method) + "Filter"
}

func goTypeFromOpenAPI(property OpenAPIProperty) (string, error) {
	if len(property.AnyOf) > 0 {
		if isStringOrStringsUnion(property) {
			return "StringOrStrings", nil
		}
		var commonType string
		for i, variant := range property.AnyOf {
			variantType, err := goTypeFromOpenAPI(variant)
			if err != nil {
				return "", err
			}
			if i == 0 {
				commonType = variantType
			} else if variantType != commonType {
				// Go has no field-level union type. Keep polymorphic input JSON intact.
				return "any", nil
			}
		}
		return commonType, nil
	}
	if len(property.Enum) > 0 {
		return "string", nil
	}
	switch property.Type {
	case "string":
		return "string", nil
	case "integer", "number":
		// WarEra describes integer-like pagination values as "number" in the spec.
		return "int", nil
	case "boolean":
		return "bool", nil
	case "array":
		if property.Items == nil {
			return "", fmt.Errorf("array is missing its item schema")
		}
		itemType, err := goTypeFromOpenAPI(*property.Items)
		if err != nil {
			return "", fmt.Errorf("array item: %w", err)
		}
		if itemType == "*bool" {
			itemType = "bool"
		}
		return "[]" + itemType, nil
	default:
		return "", fmt.Errorf("unsupported OpenAPI type %q", property.Type)
	}
}

func isStringOrStringsUnion(property OpenAPIProperty) bool {
	if len(property.AnyOf) != 2 {
		return false
	}
	hasString, hasStringArray := false, false
	for _, variant := range property.AnyOf {
		switch {
		case variant.Type == "string":
			hasString = true
		case variant.Type == "array" && variant.Items != nil && variant.Items.Type == "string":
			hasStringArray = true
		default:
			return false
		}
	}
	return hasString && hasStringArray
}

func toGoFieldName(name string) string {
	switch name {
	case "countryId":
		return "CountryID"
	case "userId":
		return "UserID"
	case "muId":
		return "MUID"
	case "warId":
		return "WarID"
	case "defenderRegionId":
		return "DefenderRegionID"
	case "regionId":
		return "RegionID"
	case "partyId":
		return "PartyID"
	case "allianceId":
		return "AllianceID"
	case "companyId":
		return "CompanyID"
	case "battleId":
		return "BattleID"
	case "roundId":
		return "RoundID"
	case "memberId":
		return "MemberID"
	case "itemCode":
		return "ItemCode"
	case "perPage":
		return "PerPage"
	case "roundNumber":
		return "RoundNumber"
	default:
		runes := []rune(name)
		if len(runes) == 0 {
			return ""
		}
		runes[0] = unicode.ToUpper(runes[0])
		result := string(runes)
		result = strings.ReplaceAll(result, "Id", "ID")
		result = strings.ReplaceAll(result, "Url", "URL")
		if unicode.IsDigit([]rune(result)[0]) {
			result = "N" + result
		}
		return result
	}
}

func capitalize(value string) string {
	if value == "" {
		return ""
	}
	runes := []rune(value)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}
