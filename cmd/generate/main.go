// --- OpenAPI Spec Structures ---

type OpenAPISpec struct {
	Paths map[string]struct {
		Post struct {
			OperationID string `json:"operationId"`
			Description string `json:"description"`
			RequestBody *struct {
				Content struct {
					JSON struct {
						Schema struct {
							Type       string                    `json:"type"`
							Properties map[string]OpenAPIProperty `json:"properties"`
							Required   []string                  `json:"required"`
						} `json:"schema"`
					} `json:"application/json"`
				} `json:"content"`
			} `json:"requestBody"`
		} `json:"post"`
	} `json:"paths"`
}

type OpenAPIProperty struct {
	Type        string           `json:"type"`
	Description string           `json:"description"`
	Enum        []string         `json:"enum"`
	Items       *OpenAPIProperty `json:"items"`
}

// --- Inference Engine Structures ---

type FieldInfo struct {
	JSONKey   string
	GoName    string
	GoType    string
	OmitEmpty bool
	Comment   string
}

type StructInfo struct {
	Name    string
	Comment string
	Fields  map[string]*FieldInfo // JSONKey -> FieldInfo
}

type Generator struct {
	structs     map[string]*StructInfo
	typeAliases map[string]string
}

func newGenerator() *Generator {
	return &Generator{
		structs:     make(map[string]*StructInfo),
		typeAliases: make(map[string]string),
	}
}

func main() {
	specPath := "spec/openapi.json"
	fixturesDir := "spec/fixtures"
	outFile := "models_gen.go"

	gen := newGenerator()

	// 1. Parse and generate request filter models from spec/openapi.json
	fmt.Printf("Parsing OpenAPI spec from %s...\n", specPath)
	openAPICode, err := gen.parseOpenAPI(specPath)
	if err != nil {
		fmt.Printf("Error processing openapi spec: %v\n", err)
		os.Exit(1)
	}

	// 2. Parse and infer response models from spec/fixtures/*.json
	fmt.Printf("Inferring models from fixtures in %s...\n", fixturesDir)
	fixturesCode, err := gen.parseFixtures(fixturesDir)
	if err != nil {
		fmt.Printf("Error processing fixtures: %v\n", err)
		os.Exit(1)
	}

	// 3. Assemble complete models_gen.go source
	var b strings.Builder
	b.WriteString("// Code generated by cmd/generate; DO NOT EDIT.\n\n")
	b.WriteString("package warera\n\n")

	b.WriteString("// --- Generic Pagination Models ---\n\n")
	b.WriteString(`// CursorPage represents a generic cursor-paginated page of items.
type CursorPage[T any] struct {
	Items      []T    ` + "`" + `json:"items"` + "`" + `
	NextCursor string ` + "`" + `json:"nextCursor,omitempty"` + "`" + `
}
`)

	b.WriteString("\n// --- Generated Request & Filter Models (parsed from spec/openapi.json) ---\n\n")
	b.WriteString(openAPICode)

	b.WriteString("\n// --- Generated Response Models (inferred from spec/fixtures/*.json) ---\n\n")
	b.WriteString(fixturesCode)

	b.WriteString("\n// --- Supplemental Domain Models ---\n\n")
	b.WriteString(gen.supplementalModels())

	// Format code using go/format
	src := []byte(b.String())
	formatted, err := format.Source(src)
	if err != nil {
		fmt.Printf("Error formatting generated Go source: %v\nOriginal:\n%s\n", err, b.String())
		os.Exit(1)
	}

	if err := os.WriteFile(outFile, formatted, 0644); err != nil {
		fmt.Printf("Error writing %s: %v\n", outFile, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s (%d bytes)\n", outFile, len(formatted))
}

// parseOpenAPI dynamically reads spec/openapi.json and extracts request filter structs.
func (g *Generator) parseOpenAPI(specPath string) (string, error) {
	specData, err := os.ReadFile(specPath)
	if err != nil {
		return "", fmt.Errorf("reading openapi spec: %w", err)
	}

	var spec OpenAPISpec
	if err := json.Unmarshal(specData, &spec); err != nil {
		return "", fmt.Errorf("unmarshaling openapi spec: %w", err)
	}

	// Known operation name overrides
	filterNames := map[string]string{
		"company.getCompanies":                          "CompanyFilter",
		"article.getArticlesPaginated":                  "ArticleFilter",
		"battle.getBattles":                             "BattleFilter",
		"user.getUsersByCountry":                        "UserFilter",
		"mu.getManyPaginated":                           "MUFilter",
		"event.getEventsPaginated":                      "EventFilter",
		"transaction.getPaginatedTransactions":          "TransactionFilter",
		"workOffer.getWorkOffersPaginated":              "WorkOfferFilter",
		"mercenaryContractAuction.getPaginatedAuctions": "AuctionFilter",
	}

	var paths []string
	for p := range spec.Paths {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var sb strings.Builder

	for _, pathKey := range paths {
		pathItem := spec.Paths[pathKey]
		opID := pathItem.Post.OperationID
		rb := pathItem.Post.RequestBody
		if rb == nil {
			continue
		}

		schema := rb.Content.JSON.Schema
		props := schema.Properties
		if len(props) == 0 {
			continue
		}

		// Check if it's in known filter names or is a query/filter operation
		structName, isKnown := filterNames[opID]
		if !isKnown {
			// Auto-derive if >= 2 parameters or contains limit/cursor
			_, hasLimit := props["limit"]
			_, hasPerPage := props["perPage"]
			_, hasCursor := props["cursor"]
			if len(props) >= 2 || hasLimit || hasPerPage || hasCursor {
				structName = deriveFilterName(opID)
			} else {
				continue
			}
		}

		sb.WriteString(fmt.Sprintf("// %s specifies query and filter options for %s.\n", structName, opID))
		sb.WriteString(fmt.Sprintf("type %s struct {\n", structName))

		var propKeys []string
		for k := range props {
			propKeys = append(propKeys, k)
		}
		sort.Strings(propKeys)

		for _, k := range propKeys {
			prop := props[k]
			goName := toGoFieldName(k, false)
			goType := toGoTypeFromOpenAPI(prop)

			comment := ""
			if prop.Description != "" {
				comment = fmt.Sprintf(" // %s", prop.Description)
			}

			sb.WriteString(fmt.Sprintf("\t%s %s `json:\"%s,omitempty\"`%s\n", goName, goType, k, comment))
		}
		sb.WriteString("}\n\n")

		fmt.Printf("  [OpenAPI] Generated %s from %s (%d properties)\n", structName, opID, len(props))
	}

	return sb.String(), nil
}

func deriveFilterName(opID string) string {
	parts := strings.Split(opID, ".")
	if len(parts) >= 2 {
		service := capitalize(parts[0])
		method := parts[1]
		if strings.HasPrefix(method, "get") {
			method = strings.TrimPrefix(method, "get")
		}
		if strings.HasSuffix(method, "Paginated") {
			method = strings.TrimSuffix(method, "Paginated")
		}
		return service + capitalize(method) + "Filter"
	}
	return capitalize(opID) + "Filter"
}

// parseFixtures reads all JSON fixtures in spec/fixtures/ and infers Go structs.
func (g *Generator) parseFixtures(fixturesDir string) (string, error) {
	files, err := filepath.Glob(filepath.Join(fixturesDir, "*.json"))
	if err != nil {
		return "", err
	}
	sort.Strings(files)

	var outputOrder []string

	for _, file := range files {
		base := filepath.Base(file)
		data, err := os.ReadFile(file)
		if err != nil {
			return "", fmt.Errorf("reading fixture %s: %w", file, err)
		}

		var raw any
		if err := json.Unmarshal(data, &raw); err != nil {
			return "", fmt.Errorf("decoding fixture JSON %s: %w", file, err)
		}

		rootName, isPaginated, isMap := determineFixtureModel(base, raw)
		fmt.Printf("  [Fixture] Processing %s -> Model: %s (paginated: %v, map: %v)\n", base, rootName, isPaginated, isMap)

		if isMap {
			g.typeAliases[rootName] = "map[string]float64"
			outputOrder = append(outputOrder, rootName)
			continue
		}

		if isPaginated {
			// Extract items array and infer item struct across all array elements
			if obj, ok := raw.(map[string]any); ok {
				if items, ok := obj["items"].([]any); ok && len(items) > 0 {
					g.inferStructFromItems(rootName, fmt.Sprintf("// %s represents a domain item inferred from %s.", rootName, base), items)
					outputOrder = append(outputOrder, rootName)
				}
			}
		} else {
			if obj, ok := raw.(map[string]any); ok {
				g.inferStructFromObject(rootName, fmt.Sprintf("// %s is inferred from %s.", rootName, base), obj)
				outputOrder = append(outputOrder, rootName)
			}
		}
	}

	// Format all inferred structs and aliases into Go code
	var sb strings.Builder

	// Write type aliases first (e.g. ItemPrices)
	for _, name := range outputOrder {
		if alias, ok := g.typeAliases[name]; ok {
			sb.WriteString(fmt.Sprintf("// %s represents market reference prices indexed by item code.\n", name))
			sb.WriteString(fmt.Sprintf("type %s %s\n\n", name, alias))
		}
	}

	// Write inferred structs in alphabetical order
	var structNames []string
	for sName := range g.structs {
		structNames = append(structNames, sName)
	}
	sort.Strings(structNames)

	for _, sName := range structNames {
		st := g.structs[sName]
		if st.Comment != "" {
			sb.WriteString(fmt.Sprintf("%s\n", st.Comment))
		}
		sb.WriteString(fmt.Sprintf("type %s struct {\n", st.Name))

		var fKeys []string
		for k := range st.Fields {
			fKeys = append(fKeys, k)
		}
		sort.Strings(fKeys)

		for _, k := range fKeys {
			f := st.Fields[k]
			tag := fmt.Sprintf("`json:\"%s\"`", f.JSONKey)
			if f.OmitEmpty {
				tag = fmt.Sprintf("`json:\"%s,omitempty\"`", f.JSONKey)
			}
			comment := ""
			if f.Comment != "" {
				comment = fmt.Sprintf(" // %s", f.Comment)
			}
			sb.WriteString(fmt.Sprintf("\t%s %s %s%s\n", f.GoName, f.GoType, tag, comment))
		}
		sb.WriteString("}\n\n")
	}

	return sb.String(), nil
}

func determineFixtureModel(filename string, raw any) (name string, isPaginated bool, isMap bool) {
	// 1. Inspect raw JSON to detect pagination and map structures dynamically
	if obj, ok := raw.(map[string]any); ok {
		if _, hasItems := obj["items"].([]any); hasItems {
			if _, hasCursor := obj["nextCursor"]; hasCursor {
				isPaginated = true
			}
		}
		if !isPaginated && isUniformFloatMap(obj) {
			isMap = true
		}
	}

	// 2. Derive canonical struct name
	switch filename {
	case "article.getArticlesPaginated.json":
		return "Article", isPaginated, isMap
	case "battle.getBattles.json":
		return "Battle", isPaginated, isMap
	case "country.getCountryById.json":
		return "Country", isPaginated, isMap
	case "gameConfig.getDates.json":
		return "GameDates", isPaginated, isMap
	case "itemTrading.getPrices.json":
		return "ItemPrices", isPaginated, isMap
	case "search.searchAnything.json":
		return "SearchResult", isPaginated, isMap
	case "user.getUserLite.json":
		return "UserLite", isPaginated, isMap
	case "user.getUserById.json":
		return "User", isPaginated, isMap
	default:
		parts := strings.Split(filename, ".")
		if len(parts) >= 2 {
			service := capitalize(parts[0])
			if isPaginated {
				return service, isPaginated, isMap
			}
			method := parts[1]
			method = strings.TrimPrefix(method, "get")
			method = strings.TrimSuffix(method, "ById")
			method = strings.TrimSuffix(method, "Paginated")
			return capitalize(method), isPaginated, isMap
		}
		return "FixtureModel", isPaginated, isMap
	}
}

// inferStructFromObject inspects a JSON object and registers/updates the struct.
func (g *Generator) inferStructFromObject(name, comment string, obj map[string]any) *StructInfo {
	st, exists := g.structs[name]
	if !exists {
		st = &StructInfo{
			Name:    name,
			Comment: comment,
			Fields:  make(map[string]*FieldInfo),
		}
		g.structs[name] = st
	}

	for k, v := range obj {
		if k == "__v" {
			continue // MongoDB internal version key
		}

		goName := toGoFieldName(k, isString(v))
		goType, omitEmpty := g.inferType(name, k, v)

		// Special case: RankingItem.Value can be int or float in different rankings
		if name == "RankingItem" && k == "value" {
			goType = "any"
		}

		existingField, fExists := st.Fields[k]
		if !fExists {
			st.Fields[k] = &FieldInfo{
				JSONKey:   k,
				GoName:    goName,
				GoType:    goType,
				OmitEmpty: omitEmpty,
			}
		} else {
			// Resolve types across instances (e.g. integer vs float, concrete slice vs empty slice fallback)
			existingField.GoType = resolveTypes(existingField.GoType, goType)
			if omitEmpty {
				existingField.OmitEmpty = true
			}
		}
	}

	return st
}

// inferStructFromItems merges multiple array elements to produce a comprehensive struct.
func (g *Generator) inferStructFromItems(name, comment string, items []any) *StructInfo {
	st, exists := g.structs[name]
	if !exists {
		st = &StructInfo{
			Name:    name,
			Comment: comment,
			Fields:  make(map[string]*FieldInfo),
		}
		g.structs[name] = st
	}

	for _, it := range items {
		m, ok := it.(map[string]any)
		if !ok {
			continue
		}
		g.inferStructFromObject(name, comment, m)
	}
	return st
}

// inferType infers the Go type string for a given JSON value.
func (g *Generator) inferType(parentStruct, fieldName string, v any) (goType string, omitEmpty bool) {
	if v == nil {
		return "any", true
	}

	switch val := v.(type) {
	case bool:
		return "bool", true
	case string:
		return "string", true
	case float64:
		// Check if whole integer
		if val == float64(int64(val)) {
			if val > 2147483647 || val < -2147483648 {
				return "int64", true
			}
			return "int", true
		}
		return "float64", true

	case []any:
		if len(val) == 0 {
			return "[]string", true
		}
		// If slice contains objects, infer element struct by merging all objects
		if _, isObj := val[0].(map[string]any); isObj {
			elemStructName := deriveNestedStructName(parentStruct, fieldName)
			g.inferStructFromItems(elemStructName, fmt.Sprintf("// %s is a nested component of %s.", elemStructName, parentStruct), val)
			return "[]" + elemStructName, true
		}
		// Otherwise primitive slice (e.g. []string)
		elemType, _ := g.inferType(parentStruct, fieldName+"Item", val[0])
		return "[]" + elemType, true

	case map[string]any:
		// Check for dynamic ID map (e.g. nonAggressionUntil: {id: date})
		if isUniformStringMap(val) {
			return "map[string]string", true
		}
		if isRankingMap(val) {
			var allRankings []any
			for _, rk := range val {
				allRankings = append(allRankings, rk)
			}
			g.inferStructFromItems("RankingItem", "// RankingItem represents a tiered leaderboard rank entry.", allRankings)
			return "map[string]RankingItem", true
		}

		// Nested struct
		nestedName := deriveNestedStructName(parentStruct, fieldName)
		g.inferStructFromObject(nestedName, fmt.Sprintf("// %s is a nested component of %s.", nestedName, parentStruct), val)

		// Use pointer for optional nested objects
		if fieldName == "currentRound" || fieldName == "strategicResources" || fieldName == "weapon" {
			return "*" + nestedName, true
		}
		return nestedName, true

	default:
		return "any", true
	}
}

// resolveTypes cleanly merges types across records without accidental downgrades to any.
func resolveTypes(existing, incoming string) string {
	if existing == incoming {
		return existing
	}
	// If one is "any" (derived from nil), prefer the concrete type
	if existing == "any" {
		return incoming
	}
	if incoming == "any" {
		return existing
	}

	// Number hierarchy: float64 > int64 > int
	isNum := func(t string) bool { return t == "int" || t == "int64" || t == "float64" }
	if isNum(existing) && isNum(incoming) {
		if existing == "float64" || incoming == "float64" {
			return "float64"
		}
		if existing == "int64" || incoming == "int64" {
			return "int64"
		}
		return "int"
	}

	// Slices: if one was empty slice fallback ([]string or []any), prefer the concrete struct slice
	if strings.HasPrefix(existing, "[]") && strings.HasPrefix(incoming, "[]") {
		if existing == "[]string" || existing == "[]any" {
			return incoming
		}
		if incoming == "[]string" || incoming == "[]any" {
			return existing
		}
	}

	return "any"
}

func deriveNestedStructName(parent, field string) string {
	cleanParent := strings.TrimSuffix(parent, "Lite")
	switch field {
	case "taxes":
		return cleanParent + "Taxes"
	case "unrest":
		return cleanParent + "Unrest"
	case "strategicResources":
		return cleanParent + "StrategicResourcesInfo"
	case "leveling":
		return "UserLeveling"
	case "stats":
		return cleanParent + "Stats"
	case "attacker", "defender":
		if cleanParent == "BattleRound" {
			return "RoundSideCombatStats"
		}
		return "BattleSideSummary"
	case "currentRound":
		return "BattleRound"
	case "live":
		return "RoundLiveState"
	case "dates":
		return cleanParent + "Dates"
	case "lastHits":
		return "RoundLastHit"
	case "equipments":
		return "RoundEquipment"
	case "weapon":
		return "RoundWeapon"
	case "skills":
		if cleanParent == "RoundEquipment" {
			return "EquipmentSkills"
		}
		if cleanParent == "RoundWeapon" {
			return "WeaponSkills"
		}
		return cleanParent + "Skills"
	default:
		return cleanParent + capitalize(field)
	}
}

// isUniformStringMap returns true only if all keys are 24-character ObjectIDs and all values are strings.
func isUniformStringMap(m map[string]any) bool {
	if len(m) == 0 {
		return false
	}
	for k, v := range m {
		if len(k) != 24 { // MUST be 24-char hex key (MongoDB ObjectID)
			return false
		}
		if _, ok := v.(string); !ok {
			return false
		}
	}
	return true
}

func isUniformFloatMap(m map[string]any) bool {
	if len(m) < 3 {
		return false
	}
	for _, v := range m {
		if _, ok := v.(float64); !ok {
			return false
		}
	}
	return true
}

func isRankingMap(m map[string]any) bool {
	if len(m) == 0 {
		return false
	}
	for _, v := range m {
		if sub, ok := v.(map[string]any); ok {
			if _, hasRank := sub["rank"]; hasRank {
				if _, hasTier := sub["tier"]; hasTier {
					return true
				}
			}
		}
	}
	return false
}

func isString(v any) bool {
	_, ok := v.(string)
	return ok
}

func capitalize(s string) string {
	if s == "" {
		return ""
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	res := string(r)
	if strings.HasSuffix(res, "Id") && len(res) > 2 {
		res = strings.TrimSuffix(res, "Id") + "ID"
	}
	if strings.HasSuffix(res, "Url") && len(res) > 3 {
		res = strings.TrimSuffix(res, "Url") + "URL"
	}
	return res
}

