// toGoTypeFromOpenAPI maps OpenAPI types to Go types.
func toGoTypeFromOpenAPI(prop OpenAPIProperty) string {
	switch prop.Type {
	case "string":
		return "string"
	case "number", "integer":
		return "int"
	case "boolean":
		return "*bool"
	case "array":
		if prop.Items != nil && prop.Items.Type == "string" {
			return "[]string"
		}
		return "[]string"
	default:
		return "string"
	}
}

