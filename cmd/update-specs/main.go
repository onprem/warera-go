package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"time"
)

const (
	openAPIURL       = "https://api2.warera.io/openapi.json"
	trpcRepository   = "https://github.com/WarEraProjects/TRPC"
	trpcCommitAPIURL = "https://api.github.com/repos/WarEraProjects/TRPC/commits/main"
	trpcResponsePath = "src/api/Responses.d.ts"
	userAgent        = "warera-go-spec-updater"
)

var commitSHA = regexp.MustCompile(`^[0-9a-f]{40}$`)

type openAPIDocument struct {
	OpenAPI string `json:"openapi"`
	Info    struct {
		Version string `json:"version"`
	} `json:"info"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "update-specs: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	specDir := filepath.Join("spec")

	commitData, err := get(trpcCommitAPIURL, true)
	if err != nil {
		return err
	}
	var commitInfo struct {
		SHA string `json:"sha"`
	}
	if err := json.Unmarshal(commitData, &commitInfo); err != nil {
		return fmt.Errorf("decode TRPC commit response: %w", err)
	}
	if !commitSHA.MatchString(commitInfo.SHA) {
		return errors.New("GitHub did not return a valid TRPC commit SHA")
	}

	responseRawURL := fmt.Sprintf(
		"https://raw.githubusercontent.com/WarEraProjects/TRPC/%s/%s",
		commitInfo.SHA,
		trpcResponsePath,
	)
	responseSource, err := get(responseRawURL, false)
	if err != nil {
		return err
	}
	if !bytes.Contains(responseSource, []byte("// Generated by Responses/convert_to_types.ts")) ||
		!bytes.Contains(responseSource, []byte("export interface ")) {
		return fmt.Errorf("%s did not look like the expected generated declarations", responseRawURL)
	}

	openAPIBytes, err := get(openAPIURL, false)
	if err != nil {
		return err
	}
	var openAPI openAPIDocument
	if err := json.Unmarshal(openAPIBytes, &openAPI); err != nil {
		return fmt.Errorf("decode OpenAPI document: %w", err)
	}
	if len(openAPI.OpenAPI) < 2 || openAPI.OpenAPI[:2] != "3." || openAPI.Info.Version == "" {
		return fmt.Errorf("%s did not return a versioned OpenAPI 3 document", openAPIURL)
	}
	var formattedOpenAPI bytes.Buffer
	if err := json.Indent(&formattedOpenAPI, openAPIBytes, "", "  "); err != nil {
		return fmt.Errorf("format OpenAPI document: %w", err)
	}
	prettyOpenAPI := append(bytes.TrimSpace(formattedOpenAPI.Bytes()), '\n')

	responseSourceURL := fmt.Sprintf("%s/blob/%s/%s", trpcRepository, commitInfo.SHA, trpcResponsePath)
	licenseURL := fmt.Sprintf("%s/blob/%s/LICENSE", trpcRepository, commitInfo.SHA)
	responseWithAttribution := []byte(fmt.Sprintf(
		"// Source: %s\n// Upstream license: see %s\n%s",
		responseSourceURL,
		licenseURL,
		responseSource,
	))

	outputs := []fileOutput{
		{path: filepath.Join(specDir, "openapi.json"), data: prettyOpenAPI},
		{path: filepath.Join(specDir, "Responses.d.ts"), data: responseWithAttribution},
	}
	changed, err := stageAndReplace(specDir, outputs)
	if err != nil {
		return err
	}

	fmt.Printf("Updated %d spec file(s).\n", changed)
	fmt.Printf("OpenAPI: %s\n", openAPI.Info.Version)
	fmt.Printf("TRPC response declarations: %s\n", commitInfo.SHA)
	return nil
}

func get(url string, githubAPI bool) ([]byte, error) {
	request, err := http.NewRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, fmt.Errorf("create request for %s: %w", url, err)
	}
	request.Header.Set("User-Agent", userAgent)
	if githubAPI {
		request.Header.Set("Accept", "application/vnd.github+json")
	}

	client := &http.Client{Timeout: 60 * time.Second}
	response, err := client.Do(request)
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", url, err)
	}
	defer response.Body.Close()
	if response.StatusCode < http.StatusOK || response.StatusCode >= http.StatusMultipleChoices {
		return nil, fmt.Errorf("download %s: HTTP %s", url, response.Status)
	}
	data, err := io.ReadAll(response.Body)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", url, err)
	}
	return data, nil
}

type fileOutput struct {
	path string
	data []byte
}

func stageAndReplace(specDir string, outputs []fileOutput) (int, error) {
	tempDir, err := os.MkdirTemp(specDir, ".update-specs-")
	if err != nil {
		return 0, fmt.Errorf("create staging directory: %w", err)
	}
	defer os.RemoveAll(tempDir)

	type stagedFile struct {
		temporary   string
		destination string
	}
	var changed []stagedFile
	for index, output := range outputs {
		temporary := filepath.Join(tempDir, fmt.Sprintf("%d", index))
		if err := os.WriteFile(temporary, output.data, 0o644); err != nil {
			return 0, fmt.Errorf("stage %s: %w", output.path, err)
		}
		current, err := os.ReadFile(output.path)
		if err == nil && bytes.Equal(current, output.data) {
			continue
		}
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return 0, fmt.Errorf("read %s: %w", output.path, err)
		}
		changed = append(changed, stagedFile{temporary: temporary, destination: output.path})
	}

	for _, file := range changed {
		if err := os.Rename(file.temporary, file.destination); err != nil {
			return 0, fmt.Errorf("replace %s: %w", file.destination, err)
		}
	}
	return len(changed), nil
}
